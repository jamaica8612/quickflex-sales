create table if not exists public.quickflex_daily_inspections (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  inspection_date date not null,
  status text not null default 'completed' check (status in ('completed', 'no_operation')),
  results jsonb not null default '{}'::jsonb check (
    jsonb_typeof(results) = 'object'
    and jsonb_array_length(jsonb_path_query_array(results, '$.*')) = 11
    and results ?& array['item_1', 'item_2', 'item_3', 'item_4', 'item_5', 'item_6', 'item_7', 'item_8', 'item_9', 'item_10', 'item_11']
    and (
      (status = 'completed' and not jsonb_path_exists(results, '$.* ? (@ != "good" && @ != "bad")'))
      or (status = 'no_operation' and not jsonb_path_exists(results, '$.* ? (@ != "no_operation")'))
    )
  ),
  defect_notes text not null default '',
  action_notes text not null default '',
  signed_name text not null,
  signed_at timestamptz not null default now(),
  source text not null default 'app' check (source in ('app', 'legacy_paper')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, inspection_date)
);

