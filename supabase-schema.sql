create table if not exists public.quickflex_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text not null default '사용자',
  driver_type text not null default 'backup' check (driver_type in ('backup', 'fixed')),
  status text not null default 'pending' check (status in ('pending', 'approved', 'blocked')),
  role text not null default 'driver' check (role in ('driver', 'admin')),
  fixed_routes text[] not null default '{}',
  goal_amount integer not null default 6000000,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

