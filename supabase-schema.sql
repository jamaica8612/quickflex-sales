create or replace function public.quickflex_apply_work_route_result(
  p_device_id text,
  p_work_id text,
  p_work_date date,
  p_work_shift text,
  p_route text,
  p_household_count integer,
  p_unit_snapshot integer,
  p_sort_order integer,
  p_delivery_count integer default null,
